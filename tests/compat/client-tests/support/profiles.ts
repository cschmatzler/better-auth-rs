/** Explicit equivalent configurations of the pinned runtime. */

function variants<P extends string, S extends string>(
  prefix: P,
  suffixes: readonly S[],
): `${P}${S}`[] {
  return suffixes.map((suffix) => `${prefix}${suffix}` as `${P}${S}`);
}

